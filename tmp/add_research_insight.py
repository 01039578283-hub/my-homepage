def fix_page(slug: str, h2: str, para: str, mention: str) -> bool:
    path = ROOT / "교육정보" / slug / "index.html"
    source = path.read_text(encoding="utf-8")
    if "edu-insight" in source:
        return False

    new_section = f'<section class="edu-section"><h2>{h2}</h2><p class="edu-insight">{para}</p></section>'
    updated, count = re.subn(
        r'(<section class="edu-section edu-faq">)',
        new_section + r"\1",
        source,
        count=1,
    )
    if count == 0:
        raise RuntimeError(f"faq anchor not found in {path}")

    m = re.search(r'(<script type="application/ld\+json">)(.*?)(</script>)', updated, re.S)
    data = json.loads(m.group(2))
    for node in data["@graph"]:
        if node.get("@type") == "Article":
            mentions = node.setdefault("mentions", [])
            if not any(x.get("name") == mention for x in mentions):
                mentions.append({"@type": "Thing", "name": mention})
    new_jsonld = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    updated = updated[: m.start()] + m.group(1) + new_jsonld + m.group(3) + updated[m.end():]

    path.write_text(updated, encoding="utf-8")
    return True


def main() -> None:
    for slug, (h2, para, mention) in CONTENT.items():
        print(f"{slug}: changed={fix_page(slug, h2, para, mention)}")


if __name__ == "__main__":
    main()
